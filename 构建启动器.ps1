[CmdletBinding()]
param(
    [string]$OutputPath = ''
)

Set-StrictMode -Version 2.0
$ErrorActionPreference = 'Stop'

$appDirectory = Split-Path -Parent $MyInvocation.MyCommand.Path
if ([string]::IsNullOrWhiteSpace($OutputPath)) {
    $OutputPath = Join-Path $appDirectory 'RoadLevelHotkeys.exe'
}

$versionPath = Join-Path $appDirectory 'version.json'
$versionInfo = Get-Content -LiteralPath $versionPath -Raw -Encoding UTF8 | ConvertFrom-Json
$version = [string]$versionInfo.version
$numericVersion = $version.TrimStart('V')

$runtimeFiles = @(
    'RoadLevelHotkeys.ps1',
    'DpiSupport.ps1',
    'Localization.ps1',
    'ConfigStorage.ps1',
    'SingleInstance.ps1',
    'ShortcutRules.ps1',
    'MouseAutomation.ps1',
    'BackupWorkflow.ps1',
    'VersionInfo.ps1',
    'version.json',
    'LayoutPolicy.ps1',
    'model_shortcuts.json',
    'LICENSE',
    '版权与使用限制.txt',
    '使用说明.md',
    '用户指南.html'
)

foreach ($relativePath in $runtimeFiles) {
    $fullPath = Join-Path $appDirectory $relativePath
    if (-not (Test-Path -LiteralPath $fullPath -PathType Leaf)) {
        throw "缺少运行时文件：$fullPath"
    }
}

$manifestLines = New-Object System.Collections.Generic.List[string]
foreach ($relativePath in $runtimeFiles) {
    $hash = (Get-FileHash -LiteralPath (Join-Path $appDirectory $relativePath) -Algorithm SHA256).Hash
    $manifestLines.Add("$hash  $relativePath")
}

$manifestPath = Join-Path $appDirectory 'runtime.sha256'
$manifestText = ($manifestLines -join "`n") + "`n"
[System.IO.File]::WriteAllText(
    $manifestPath,
    $manifestText,
    [System.Text.UTF8Encoding]::new($false)
)
$manifestHash = (Get-FileHash -LiteralPath $manifestPath -Algorithm SHA256).Hash
$generatedSource = @"
// Generated by 构建启动器.ps1. Do not edit manually.
namespace RoadLevel
{
    internal static class RuntimeManifestHash
    {
        public const string Sha256 = "$manifestHash";
    }
}
"@
[System.IO.File]::WriteAllText(
    (Join-Path $appDirectory 'RuntimeManifestHash.g.cs'),
    $generatedSource,
    [System.Text.UTF8Encoding]::new($false)
)

$csc = Join-Path $env:SystemRoot 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'
if (-not (Test-Path -LiteralPath $csc)) {
    throw "缺少C#编译器：$csc"
}

$buildPath = Join-Path $appDirectory 'RoadLevelHotkeys.build.exe'
$outputFull = [System.IO.Path]::GetFullPath($OutputPath)
$appPrefix = [System.IO.Path]::GetFullPath($appDirectory).TrimEnd('\') + '\'
if (-not $outputFull.StartsWith($appPrefix, [System.StringComparison]::OrdinalIgnoreCase)) {
    throw "输出路径越界：$outputFull"
}

& $csc `
    /nologo `
    /target:winexe `
    /platform:anycpu `
    /optimize+ `
    /win32manifest:app.manifest `
    /out:$buildPath `
    /reference:System.Windows.Forms.dll `
    /reference:System.Drawing.dll `
    Launcher.cs `
    RuntimeIntegrity.cs `
    RuntimeManifestHash.g.cs
if ($LASTEXITCODE -ne 0) {
    throw "启动器编译失败，退出码=$LASTEXITCODE"
}

$fileVersion = [System.Diagnostics.FileVersionInfo]::GetVersionInfo($buildPath).FileVersion
if ($fileVersion -ne "$numericVersion.0") {
    throw "EXE文件版本错误：$fileVersion，期望=$numericVersion.0"
}
Move-Item -LiteralPath $buildPath -Destination $outputFull -Force

Write-Output "已生成：$outputFull"
Write-Output "版本：$version"
Write-Output "运行时清单SHA256：$manifestHash"
